const savedLanguage = (() => {
  try {
    return (['en', 'pt', 'pl'].includes(localStorage.getItem('vpm-language') || '') ? localStorage.getItem('vpm-language') : 'en')
  } catch {
    return 'en'
  }
})()

void i18n.use(initReactI18next).init({
  resources: { ...translations, pt },
  lng: savedLanguage,
  fallbackLng: 'en',
  supportedLngs: ['en', 'pt', 'pl'],
  interpolation: { escapeValue: false },
})

export default i18n
