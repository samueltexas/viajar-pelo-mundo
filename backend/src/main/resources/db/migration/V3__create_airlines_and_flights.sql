CREATE TABLE airlines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    iata_code VARCHAR(2) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    country_code VARCHAR(2) NOT NULL,

    created_at TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_airline_iata_length
        CHECK (LENGTH(iata_code) = 2)
);

CREATE TABLE flights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    flight_number VARCHAR(10) NOT NULL,

    airline_id BIGINT NOT NULL,
    origin_airport_id BIGINT NOT NULL,
    destination_airport_id BIGINT NOT NULL,

    departure_time TIMESTAMP WITH TIME ZONE NOT NULL,
    arrival_time TIMESTAMP WITH TIME ZONE NOT NULL,

    base_price NUMERIC(12, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'EUR',

    total_seats INTEGER NOT NULL,
    available_seats INTEGER NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',

    created_at TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_flights_airline
        FOREIGN KEY (airline_id) REFERENCES airlines(id),

    CONSTRAINT fk_flights_origin
        FOREIGN KEY (origin_airport_id) REFERENCES airports(id),

    CONSTRAINT fk_flights_destination
        FOREIGN KEY (destination_airport_id) REFERENCES airports(id),

    CONSTRAINT chk_flight_airports_different
        CHECK (origin_airport_id <> destination_airport_id),

    CONSTRAINT chk_flight_times
        CHECK (arrival_time > departure_time),

    CONSTRAINT chk_flight_price
        CHECK (base_price >= 0),

    CONSTRAINT chk_flight_total_seats
        CHECK (total_seats > 0),

    CONSTRAINT chk_flight_available_seats
        CHECK (available_seats >= 0 AND available_seats <= total_seats)
);

CREATE INDEX idx_flights_route_departure
    ON flights (
        origin_airport_id,
        destination_airport_id,
        departure_time
    );

CREATE INDEX idx_flights_airline
    ON flights (airline_id);
