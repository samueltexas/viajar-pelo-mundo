-- Pagamentos fictícios para demonstrar o ciclo de uma reserva.
-- Não existem dados bancários nem integração com serviços financeiros.

CREATE TABLE demo_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL UNIQUE REFERENCES bookings(id),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    amount NUMERIC(12,2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_demo_payment_status CHECK (
        status IN ('PENDING', 'PAID', 'FAILED', 'REFUNDED', 'CANCELLED')
    ),
    CONSTRAINT chk_demo_payment_amount CHECK (amount >= 0)
);

CREATE INDEX idx_demo_payments_status ON demo_payments(status);
