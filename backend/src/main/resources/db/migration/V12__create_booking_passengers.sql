-- Guarda os passageiros associados a cada reserva.
-- Reservas antigas continuam válidas sem registos nesta tabela.

CREATE TABLE booking_passengers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id),
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    date_of_birth DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_passenger_first_name
        CHECK (LENGTH(TRIM(first_name)) > 0),

    CONSTRAINT chk_passenger_last_name
        CHECK (LENGTH(TRIM(last_name)) > 0)
);

CREATE INDEX idx_booking_passengers_booking_id
    ON booking_passengers(booking_id);
