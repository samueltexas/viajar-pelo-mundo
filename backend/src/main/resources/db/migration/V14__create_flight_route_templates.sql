-- Modelos de rotas para geração automática de voos.
-- Não altera os voos ou reservas existentes.

CREATE TABLE flight_route_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    flight_number VARCHAR(10) NOT NULL UNIQUE,

    airline_id BIGINT NOT NULL
        REFERENCES airlines(id),

    origin_airport_id BIGINT NOT NULL
        REFERENCES airports(id),

    destination_airport_id BIGINT NOT NULL
        REFERENCES airports(id),

    departure_hour INTEGER NOT NULL,

    duration_hours INTEGER NOT NULL,

    base_price NUMERIC(12, 2) NOT NULL,

    currency VARCHAR(3) NOT NULL DEFAULT 'EUR',

    total_seats INTEGER NOT NULL DEFAULT 180,

    active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_template_airports_different
        CHECK (origin_airport_id <> destination_airport_id),

    CONSTRAINT chk_template_departure_hour
        CHECK (departure_hour BETWEEN 0 AND 23),

    CONSTRAINT chk_template_duration
        CHECK (duration_hours BETWEEN 1 AND 30),

    CONSTRAINT chk_template_price
        CHECK (base_price >= 0),

    CONSTRAINT chk_template_seats
        CHECK (total_seats > 0)
);
